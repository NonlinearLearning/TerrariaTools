// P02 plan-construction and repeated-traversal reuse.
//
// Three independent layers, deliberately kept apart so a pass here cannot be produced by
// accidentally weakening another:
//
//  1. Frozen oracle. Sparse / Collision / JoinLoop are built through the real production path
//     (BuildFromSource) and compared against the complete ordered graph, the candidate
//     publication sequence, the per-method scalar outcome and the raw/unique candidate counts
//     that the PRE-P02 binary produced. P02 must not move any of them.
//
//  2. T2 structural guards. The zero-FactCount short-circuit is a pure skip, so it must be
//     observable as work removed and never as work added: fact-free operations stop visiting
//     candidate predecessors, while an operation that DOES carry a fact keeps the pre-existing
//     "cleared then found empty" path unchanged.
//
//  3. Counter scoping. Per-method probes are not accumulated across methods in one document and
//     not accumulated across repeated BuildFromSource calls on a reused builder.
//
// The oracle is deliberately NOT DataFlowGraphSnapshot + SHA256: Capture() serializes the
// resolved *absolute* FullName, so its hash depends on the process working directory (the
// measurement host runs from the repo root, the test host from Build/test/Debug/net10.0).
// The normalized graph hash below uses only graph-owned raw fields (interned string-table IDs,
// spans, stable anchors) plus the full edge list, so it is working-directory independent while
// still covering the complete ordered graph.
public sealed class DataFlowPlanConstructionReuseTests {
  // Frozen PRE-P02 oracle. Generated by building each fixture through BuildFromSource with
