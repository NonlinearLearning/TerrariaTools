  // T1 required guard: a fact-free operation keeps its CFG/fixpoint result but stops reaching
  // candidate predecessors. ZeroFactChain is 24 nested blocks whose declarations are all
  // constants, so every ordered operation is fact-free and every one of them has a real CFG
  // predecessor. RED before T2: CandidatePredecessorVisits and CandidateUnions are 24 (one per
  // operation) with zero skips. GREEN after: both are 0 and every operation is skipped, while
  // the fixpoint still enqueues and dequeues each flow node and the candidate publication is
  // unchanged.
  [Fact]
  public void BuildFromSource_FactFreeOperations_KeepFixpointButSkipCandidatePredecessors() {
    var result = Build(DataFlowMeasurementSources.ZeroFactChain(), "guards/ZeroFactChain.cs");
    var counters = result.Diagnostic.Counters;

    // The short-circuit did fire for every operation...
    Assert.Equal(147, counters["CandidateOperationVisits"]);
    Assert.Equal(147, counters["CandidateZeroFactSkips"]);
    // ...and it removed exactly the candidate-stage predecessor work.
    Assert.Equal(0, counters["CandidatePredecessorVisits"]);
    Assert.Equal(0, counters["CandidateUnions"]);
    Assert.Equal(0, counters["UsedFactVisits"]);
    Assert.Equal(0, counters["TryGetCandidatesCalls"]);

    // The fixpoint is untouched: every flow node still enters and leaves the worklist, and the
    // definition stage still visits every ordered operation.
    Assert.Equal(149, counters["Enqueues"]);
    Assert.Equal(149, counters["Dequeues"]);
    Assert.Equal(149, counters["SetComparisons"]);
    Assert.Equal(26, counters["FixpointPredecessorVisits"]);
    Assert.Equal(147, counters["DefinitionOperationVisits"]);
    Assert.Equal(147, counters["ExplicitOperationVisits"]);
    Assert.Equal(149, result.Diagnostic.Metrics.FlowNodeCount);
    Assert.Equal(24, result.Diagnostic.Metrics.DefinitionCount);

    // And the observable result is unchanged: 28 candidates survive the skip, both raw and
    // unique, because the candidates come from explicit sources and the return boundary.
    Assert.Equal(28, result.Diagnostic.Metrics.RawCandidateCount);
    Assert.Equal(28, result.Diagnostic.Metrics.UniqueCandidateCount);
    Assert.Equal(28, result.Graph.Edges.Count(edge => edge.Kind == NLCPGEdgeKind.DataFlow));
    Assert.Equal("Complete", result.Diagnostic.ExitReason);
  }

  // T1 required guard: a fact-bearing operation whose in-set is empty stays on the ORIGINAL
  // "cleared then found empty" path and must not be reclassified as a zero-fact operation.
  // `Field` is a real direct used fact, so the guard must not fire; the operation clears the
  // incoming slot, finds no predecessors at all, and short-circuits on IsEmpty before walking
  // any used fact. This is the contrast that keeps the two classes distinct.
  [Fact]
  public void BuildFromSource_FactBearingOperationWithEmptyInSet_KeepsOriginalEmptyPath() {
    var result = Build(DataFlowMeasurementSources.FactWithEmptyIncomingSet(),
        "guards/FactWithEmptyIncomingSet.cs");
    var counters = result.Diagnostic.Counters;

    // Not a zero-fact operation: the guard never fires.
    Assert.Equal(0, counters["CandidateZeroFactSkips"]);
    Assert.Equal(3, counters["CandidateOperationVisits"]);
    // Pre-existing empty-in-set behaviour, unchanged by T2: the predecessor loop runs (and
    // finds nothing), then IsEmpty short-circuits before any fact is enumerated.
    Assert.Equal(0, counters["CandidatePredecessorVisits"]);
    Assert.Equal(0, counters["CandidateUnions"]);
    Assert.Equal(0, counters["UsedFactVisits"]);
    Assert.Equal(0, counters["ReturnedCandidates"]);
    // The used fact was still discovered, and the stages T2 must not touch still ran.
    Assert.Equal(1, counters["DirectUsedFacts"]);
    Assert.Equal(3, counters["DefinitionOperationVisits"]);
    Assert.Equal(1, counters["ExplicitSourceVisits"]);
    Assert.Equal(3, counters["ReturnScanVisits"]);
    Assert.Equal(4, result.Diagnostic.Metrics.UniqueCandidateCount);
    Assert.Equal("Complete", result.Diagnostic.ExitReason);
  }

  // The contrast case for the guard above: the same fact-bearing shape, but with a non-empty
  // in-set, so the candidate stage genuinely reaches the index lookup. Together the two tests
  // pin that the short-circuit distinguishes "no fact at all" from "fact but empty in-set".
  [Fact]
  public void BuildFromSource_FactBearingOperationWithInSet_ReachesIndexLookup() {
    var result = Build(DataFlowMeasurementSources.FactWithIncomingSet(),
        "guards/FactWithIncomingSet.cs");
    var counters = result.Diagnostic.Counters;

    Assert.Equal(0, counters["CandidateZeroFactSkips"]);
    Assert.Equal(1, counters["CandidatePredecessorVisits"]);
    Assert.Equal(1, counters["CandidateUnions"]);
    Assert.Equal(1, counters["UsedFactVisits"]);
    Assert.Equal(1, counters["TryGetCandidatesCalls"]);
    Assert.Equal(1, counters["ReturnedCandidates"]);
    Assert.Equal(5, result.Diagnostic.Metrics.UniqueCandidateCount);
  }

  // A method holding both classes at once: the skip must be selective, not all-or-nothing.
  // Measured before T2 CandidatePredecessorVisits is 3, after it is 2; the skips are exactly the
  // 9 fact-free operations.
  [Fact]
  public void BuildFromSource_MixedFactOperations_SkipOnlyTheFactFreeOnes() {
    var result = Build(DataFlowMeasurementSources.AllZeroFactMethod(), "guards/AllZeroFact.cs");
    var counters = result.Diagnostic.Counters;

    Assert.Equal(16, counters["CandidateOperationVisits"]);
    Assert.Equal(9, counters["CandidateZeroFactSkips"]);
    Assert.Equal(2, counters["CandidatePredecessorVisits"]);
    Assert.Equal(2, counters["CandidateUnions"]);
    // The 7 non-skipped operations still ran, and the result did not move.
    Assert.Equal(7, result.Diagnostic.Metrics.RawCandidateCount);
    Assert.Equal(7, result.Diagnostic.Metrics.UniqueCandidateCount);
    Assert.Equal(18, counters["Enqueues"]);
    Assert.Equal(18, counters["Dequeues"]);
  }

  // T5 budget prefix: the T2 skip only removes candidate attempts that could not contribute, so
  // the pre-dedup budget count and the overflow prefix must be identical to the pre-T2 outcome at
  // every boundary. Measured across budgets 1/2/7/8/27/28/29/262/263 on four fixtures: the only
  // difference is the CandidateZeroFactSkips counter itself; raw, unique, published, overflow
  // reason, exit reason and committed DataFlow edges never move.
  [Theory]
  [InlineData(1, "CandidateEdgeLimitExceeded")]
  [InlineData(2, "CandidateEdgeLimitExceeded")]
  [InlineData(7, "CandidateEdgeLimitExceeded")]
  [InlineData(8, "CandidateEdgeLimitExceeded")]
  [InlineData(27, "CandidateEdgeLimitExceeded")]
  [InlineData(28, "Complete")]
  [InlineData(29, "Complete")]
  [InlineData(262, "Complete")]
  [InlineData(263, "Complete")]
  public void BuildFromSource_ZeroFactChainCandidateBudget_KeepsBudgetPrefix(int budget,
      string expectedExit) {
    var result = Build(DataFlowMeasurementSources.ZeroFactChain(), "measurement/ZeroFactChain.cs",
        budget);

    Assert.Equal(expectedExit, result.Diagnostic.ExitReason);
    Assert.Equal(expectedExit == "Complete" ? "None" : "CandidateEdgeLimitExceeded",
        result.Diagnostic.Metrics.OverflowReason.ToString());
    if (expectedExit == "Complete") {
      // The full 28-candidate set survives the 147 skipped operations.
      Assert.Equal(28, result.Diagnostic.Metrics.RawCandidateCount);
      Assert.Equal(28, result.Diagnostic.Metrics.UniqueCandidateCount);
      Assert.Equal(28, result.Diagnostic.PublicationOrder.Count);
      Assert.Equal(28, result.Graph.Edges.Count(edge => edge.Kind == NLCPGEdgeKind.DataFlow));
    } else {
      // Truncated at the budget, and the computation is pre-dedup: one over the budget is
      // attempted, then rejected, so nothing is published or committed.
      Assert.Equal(budget + 1, result.Diagnostic.Metrics.RawCandidateCount);
      Assert.Equal(budget, result.Diagnostic.Metrics.UniqueCandidateCount);
      Assert.Empty(result.Diagnostic.PublicationOrder);
      Assert.DoesNotContain(result.Graph.Edges, edge => edge.Kind == NLCPGEdgeKind.DataFlow);
    }
    // The guard's own counter is method-local and unaffected by the budget.
    Assert.Equal(147, result.Diagnostic.Counters["CandidateZeroFactSkips"]);
  }

  // T5 DOP equivalence: parallel solving must not change the observable result. DOP=2 is an
  // equivalence check only; all timing evidence is taken at DOP=1.
  [Fact]
  public void BuildFromSource_CollisionAtDopTwo_MatchesDopOne() {
    var serial = Build(DataFlowMeasurementSources.Collision(), "measurement/Collision.cs");
    var parallel = Build(DataFlowMeasurementSources.Collision(), "measurement/Collision.cs",
        degreeOfParallelism: 2);

    Assert.Equal(serial.Diagnostic.Metrics.UniqueCandidateCount,
        parallel.Diagnostic.Metrics.UniqueCandidateCount);
    Assert.Equal(serial.Diagnostic.Metrics.RawCandidateCount,
        parallel.Diagnostic.Metrics.RawCandidateCount);
    Assert.Equal(serial.Diagnostic.Metrics.OverflowReason,
        parallel.Diagnostic.Metrics.OverflowReason);
    Assert.Equal(serial.Diagnostic.ExitReason, parallel.Diagnostic.ExitReason);
    Assert.Equal(PublicationHash(serial.Diagnostic), PublicationHash(parallel.Diagnostic));
    Assert.Equal(serial.Graph.GraphSnapshotVersion, parallel.Graph.GraphSnapshotVersion);
    Assert.Equal(NormalizedGraphHash(serial.Graph), NormalizedGraphHash(parallel.Graph));
  }

  // Counters must be method-local: neither accumulated across the two methods of one document
  // nor across repeated BuildFromSource calls on a reused builder. AllZeroFactMethod is used
  // because it contains BOTH classes (9 fact-free skips and 2 fact-bearing predecessor visits),
  // so a leaked counter would move one of them to 18 / 4.
  [Fact]
  public void BuildFromSource_TwoMethodsAndRepeatedBuilds_KeepCountersMethodLocal() {
    var builder = CreateBuilder();
    string doubled = DataFlowMeasurementSources.AllZeroFactMethod()
            .Replace("static int Run", "static int First")
        + DataFlowMeasurementSources.AllZeroFactMethod().Replace("class Sample", "class Other");

    builder.BuildFromSource(doubled, "guards/TwoMethods.cs");
    Assert.Equal(2, builder.LastDataFlowDiagnostics.Count);
    var first = builder.LastDataFlowDiagnostics[0].Counters;
    var second = builder.LastDataFlowDiagnostics[1].Counters;
    Assert.Equal(first, second);
    // Exactly one method's worth of each, not the sum of both.
    Assert.Equal(9, first["CandidateZeroFactSkips"]);
    Assert.Equal(2, first["CandidatePredecessorVisits"]);
    Assert.Equal(16, first["CandidateOperationVisits"]);

    builder.BuildFromSource(DataFlowMeasurementSources.AllZeroFactMethod(), "guards/Repeat.cs");
    var firstRun = Assert.Single(builder.LastDataFlowDiagnostics).Counters;
    builder.BuildFromSource(DataFlowMeasurementSources.AllZeroFactMethod(), "guards/Repeat.cs");
    var secondRun = Assert.Single(builder.LastDataFlowDiagnostics).Counters;
    Assert.Equal(firstRun, secondRun);
    Assert.Equal(9, secondRun["CandidateZeroFactSkips"]);
    Assert.Equal(2, secondRun["CandidatePredecessorVisits"]);
  }

  private static (NLCPGGraph Graph, DataFlowDiagnosticResult Diagnostic) Build(
      string source, string document, int? candidateBudget = null, int degreeOfParallelism = 1) {
    var builder = CreateBuilder(candidateBudget, degreeOfParallelism);
    var graph = builder.BuildFromSource(source, document);
    return (graph, Assert.Single(builder.LastDataFlowDiagnostics));
  }

  private static NLCPGBuilder CreateBuilder(int? candidateBudget = null,
      int degreeOfParallelism = 1) {
    var dataFlowOptions = NLCPGDataFlowOptions.Unbounded;
    if (candidateBudget is { } budget) {
      dataFlowOptions = dataFlowOptions with { MaxCandidateEdgesPerMethod = budget };
    }

    return new NLCPGBuilder(NLCPGBuilderOptions.CreateDefault() with {
      MaxDegreeOfParallelism = degreeOfParallelism,
      LargeFileLineThreshold = 1, LargeFileMethodThreshold = 1,
      LargeMethodLineSpanThreshold = 1, SyntaxLargeFileLineThreshold = 1,
      DataFlowOptions = dataFlowOptions,
    }) { DataFlowDiagnostics = new(DataFlowDiagnosticMode.Detailed, "reuse", "fixture") };
  }

  // The same serialization the measurement host uses, so the frozen publication identity can be
  // compared without re-deriving the host's JSON options.
  private static readonly JsonSerializerOptions JsonOptions = new() {
    Converters = { new JsonStringEnumConverter() },
  };

  private static string PublicationHash(DataFlowDiagnosticResult diagnostic) {
    return Sha256(JsonSerializer.Serialize(diagnostic.PublicationOrder, JsonOptions));
  }

  private static string MaterialsHash(DataFlowDiagnosticResult diagnostic) {
    return Sha256(JsonSerializer.Serialize(new {
      diagnostic.Document, diagnostic.MethodSignature, diagnostic.SpanStart, diagnostic.SpanEnd,
      diagnostic.StableOrder, diagnostic.Metrics, diagnostic.ExitReason,
    }, JsonOptions));
  }

  // Path-independent normalized graph: raw graph-owned fields plus the complete ordered edge
  // list, with no resolved absolute file path.
  private static string NormalizedGraphHash(NLCPGGraph graph) {
    return Sha256(JsonSerializer.Serialize(new {
      Nodes = graph.Nodes.Select(node => new {
        node.Kind, node.NameId, node.FullNameId, node.SignatureId, node.DispatchKind,
        node.TypeFullNameId, node.FilePathId, node.SpanStart, node.SpanEnd, node.IsImplicit,
        node.NodeId, node.StableAnchor,
      }).ToArray(),
      Edges = graph.Edges.ToArray(),
    }, JsonOptions));
  }

  private static string Sha256(string payload) {
    return Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(payload)));
  }
